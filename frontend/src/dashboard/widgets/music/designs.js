export const DEFAULT_MUSIC_DESIGN = 'media-md-01'

export function getMusicDesign(designId) {
  if (!designId) return MUSIC_PLAYERS[5] // default classic (media-md-01)
  const query = String(designId).toLowerCase()
  const found = MUSIC_PLAYERS.find(p => p.id === query || p.legacyId === query || p.layout === query)
  if (found) return found

  if (query.startsWith('now-playing-')) {
    const num = Number(query.split('-').at(-1))
    return MUSIC_PLAYERS.find(p => p.index === num - 1) || MUSIC_PLAYERS[5]
  }

  const byNum = MUSIC_PLAYERS.find(p => p.number === String(designId).padStart(2, '0'))
  if (byNum) return byNum

  return MUSIC_PLAYERS[5]
}

