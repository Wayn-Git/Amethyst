import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
import { existsSync, readdirSync } from 'node:fs'
import { join } from 'node:path'
const cache = join(process.env.HOME, '.cache/ms-playwright')
const executablePath = process.env.CHROMIUM_PATH || readdirSync(cache).filter(n => n.startsWith('chromium-')).sort().reverse().map(n => join(cache,n,'chrome-linux64/chrome')).find(existsSync)
const browser = await chromium.launch({ executablePath, args:['--no-sandbox'] })
try {
 const page = await browser.newPage()
 const visit = async group => {
  await page.goto(`${process.env.BASE || 'http://127.0.0.1:5178'}/dev/widgets?group=${group}`)
  await page.locator('.home-widget').first().waitFor()
  await page.evaluate(() => {
   window.fixtureCalls = []
   const fetch = window.fetch
   window.fetch = (url, options = {}) => { window.fixtureCalls.push({ url, method: options.method, body: options.body && JSON.parse(options.body) }); return fetch(url, options) }
  })
 }
 const widget = id => page.locator(`[data-widget="${id}"]`).first()
 await visit('library')
 const capture = widget('lib.capture')
 await capture.getByLabel('Note title').fill('Keyboard sample')
 await capture.getByLabel('Note text').fill('Sample content')
 await capture.getByRole('button', { name:'Review note', exact:true }).click()
 await capture.getByRole('button', { name:'Approve save' }).waitFor()
 let calls = await page.evaluate(() => window.fixtureCalls)
 assert(calls.some(c => c.url.endsWith('/actions/add') && c.body.text === 'Sample content'))
 assert(!calls.some(c => c.url.includes('/drafts/')), 'Proposal must precede approval')
 await capture.getByRole('button', { name:'Reject save' }).click()
 calls = await page.evaluate(() => window.fixtureCalls)
 assert(calls.some(c => c.url.includes('/drafts/') && c.body.approved === false))
 await visit('agent')
 const skills = widget('agent.skills')
 await skills.getByRole('switch').focus()
 await page.keyboard.press('Space')
 await skills.getByRole('button', { name:'Approve change' }).waitFor()
 calls = await page.evaluate(() => window.fixtureCalls)
 assert(calls.some(c => c.url.endsWith('/actions/toggle') && c.body.enabled === false))
 await skills.getByRole('button', { name:'Reject change' }).click()
 const jobs = widget('agent.jobs')
 await jobs.locator('summary', { hasText:'New job' }).click()
 await jobs.getByLabel('Title', { exact:true }).fill('Sample job')
 await jobs.getByLabel('Prompt', { exact:true }).fill('Sample prompt')
 await jobs.getByLabel('Run at').fill('2099-01-01T12:00')
 await jobs.getByRole('button', { name:'Review job', exact:true }).click()
 await jobs.getByRole('button', { name:'Approve change' }).waitFor()
 await jobs.getByRole('button', { name:'Approve change' }).click()
 calls = await page.evaluate(() => window.fixtureCalls)
 assert(calls.some(c => c.url.endsWith('/actions/add') && c.body.title === 'Sample job'))
 assert(calls.some(c => c.url.includes('/drafts/') && c.body.approved === true))
 await visit('tasks')
 const goal = widget('task.goals')
 assert.match(await goal.locator('svg[role="img"]').getAttribute('aria-label'), /60 \/ 100/)
 const habit = widget('task.habits')
 assert.equal(await habit.getByRole('meter').getAttribute('aria-valuenow'), '3')
 assert.equal(await habit.getByRole('meter').getAttribute('aria-valuemax'), '5')
 await habit.getByRole('button', { name:'Check in Sample: read each morning' }).click()
 await habit.getByRole('button', { name:'Reject change' }).click()
 const agenda = widget('task.agenda')
 await agenda.getByRole('radio', { name:'Agenda', exact:true }).focus()
 await page.keyboard.press('ArrowRight')
 assert.equal(await agenda.getByRole('radio', { name:'Week', exact:true }).getAttribute('aria-checked'), 'true')
 await visit('dashboard')
 const quiet = widget('dash.quiet')
 await quiet.getByLabel('Enable quiet hours').check()
 await quiet.getByRole('button', { name:'Save quiet hours' }).click()
 await page.getByText('Sample action only. Nothing was changed outside this gallery.').waitFor()
 console.log('PASS: native form submission, proposal/approval/rejection, keyboard switch/segments, real numeric visuals, quiet checkbox')
} finally { await browser.close() }
